/* eslint-disable @typescript-eslint/no-require-imports -- Node QA harness reuses the existing CommonJS capture tools. */
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.QA_BASE_URL || 'http://127.0.0.1:3100'
const out = path.join(__dirname, '../qa/landing')
fs.mkdirSync(out, { recursive: true })
const passed = []
const check = (name) => { passed.push(name); console.log('PASS', name) }

async function main() {
  const browser = await chromium.launch({ headless: true })
  const context = await browser.newContext({ locale: 'id-ID', viewport: { width: 1440, height: 1000 } })
  let authenticated = false, loginSucceeds = false
  const resetPayloads = []
  let resetMode = 'invalid', releaseReset
  const requests = [], errors = []
  await context.route('**/api/**', async route => {
    const request = route.request(), url = new URL(request.url()), p = url.pathname
    requests.push({ path: p, method: request.method(), query: url.search })
    const json = (body, status = 200) => route.fulfill({ status, contentType: 'application/json', body: JSON.stringify(body) })
    if (p === '/api/auth/reset-password') {
      resetPayloads.push(request.postDataJSON())
      if (resetMode === 'invalid') return json({ error: 'Invalid secret key' }, 403)
      if (resetMode === 'network') return route.abort('failed')
      await new Promise(resolve => { releaseReset = resolve })
      return json({ success: true })
    }
    if (p === '/api/auth/login') { if (!loginSucceeds) return json({ error: 'Username atau password salah.' }, 401); authenticated = true; return json({ success: true }) }
    if (p === '/api/auth/logout') { authenticated = false; return json({ success: true }) }
    if (p === '/api/auth/me') return json(authenticated ? { user: { id: 77, username: 'Demo QA' } } : { error: 'Unauthorized' }, authenticated ? 200 : 401)
    if (p === '/api/auth/refresh') return json({}, authenticated ? 200 : 401)
    if (!authenticated) return json({ error: 'Unauthorized' }, 401)
    if (p === '/api/invoice') return json({ data: [], pagination: { page: 1, limit: 10, total: 0, totalPages: 0 } })
    if (p === '/api/invoice/trash/list' || p === '/api/signature') return json(p.includes('trash') ? { data: [] } : [])
    if (p === '/api/transaksi/search') return json({ results: [] })
    if (p === '/api/stats') return json({ counts: { invoices: 0, transactions: 0, signatures: 0 }, storage: { signatureKB: 0, totalMB: 0 }, database: { sizeBytes: 0, sizeMB: 0, limitMB: 512, usagePercent: 0 }, updatedAt: '2026-10-08T00:00:00Z' })
    return json({ error: 'Unhandled QA endpoint' }, 501)
  })
  try {
    const page = await context.newPage()
    page.on('pageerror', e => errors.push(e.message))
    await page.goto(base, { waitUntil: 'networkidle' })
    await page.waitForURL(base + '/login')
    await page.getByRole('heading', { name: 'Selamat datang kembali' }).waitFor()
    for (const route of ['/', '/id', '/en']) {
      const response = await context.request.get(base + route + '?source=bookmark', { maxRedirects: 0, headers: { cookie: 'klk_landing_locale=en', 'accept-language': 'en-US', 'x-vercel-ip-country': 'US' } })
      assert.equal(response.status(), 307)
      assert.equal(response.headers().location, '/login?source=bookmark')
    }
    for (const route of ['/fr', '/id/opengraph-image', '/sitemap.xml']) assert.equal((await context.request.get(base + route)).status(), 404)
    assert.ok(!(await (await context.request.get(base + '/robots.txt')).text()).includes('Sitemap:'))
    assert.equal(await page.getByText('Kembali ke beranda', { exact: false }).count(), 0)
    check('Root and old landing URLs redirect to login regardless of language; removed landing SEO returns 404')
    for (const route of ['/dashboard','/signatures','/storage','/trash']) {
      await page.goto(base + route)
      await page.waitForURL('**/login')
      await page.getByRole('heading',{name:'Selamat datang kembali'}).waitFor()
    }
    assert.ok(!requests.some(r=>!r.path.startsWith('/api/auth/')), 'No protected queries before login')
    check('All four application routes reject unauthenticated visitors before fetching business data')
    assert.match(await page.locator('meta[name="robots"]').first().getAttribute('content'), /noindex/)
    await page.setViewportSize({width:390,height:844})
    await page.screenshot({ path: path.join(out,'login-mobile.png'), fullPage:true })
    await page.setViewportSize({width:1440,height:1000})
    await page.screenshot({ path: path.join(out,'login-desktop.png'), fullPage:true })
    await page.getByLabel('Password',{exact:true}).fill('example-only')
    await page.getByRole('button',{name:'Tampilkan password',exact:true}).click()
    assert.equal(await page.locator('#password').getAttribute('type'),'text')
    await page.getByRole('button',{name:'Lupa password?'}).click()
    assert.equal(await page.locator('dialog').evaluate(el=>el.open),true)
    for (let i=0;i<5;i++) { await page.keyboard.press('Tab'); assert.ok(await page.evaluate(()=>document.activeElement === document.body || Boolean(document.activeElement.closest('dialog'))), 'Reset dialog keeps keyboard focus') }
    await page.keyboard.press('Escape')
    assert.equal(await page.locator('dialog').count(),0)
    check('Login metadata, password visibility, accessible reset dialog and Escape dismissal')
    await page.getByRole('button',{name:'Lupa password?'}).click()
    await page.getByLabel('Private Key',{exact:true}).fill('qa-private-key')
    await page.keyboard.press('Enter')
    assert.equal(resetPayloads.length,0,'Key entry alone must not reset a password')
    await page.keyboard.press('Escape')
    assert.equal(resetPayloads.length,0,'Cancelling must not reset a password')
    await page.getByRole('button',{name:'Lupa password?'}).click()
    assert.equal(await page.getByLabel('Private Key',{exact:true}).inputValue(),'')
    const savePassword = page.getByRole('button',{name:'Simpan Password Baru',exact:true})
    await page.getByLabel('Private Key',{exact:true}).fill('qa-private-key')
    await page.getByLabel('Password Baru',{exact:true}).fill('short')
    await page.getByLabel('Konfirmasi Password',{exact:true}).fill('short')
    assert.equal(await savePassword.isDisabled(),true)
    await page.getByLabel('Password Baru',{exact:true}).fill('qa-chosen-password')
    assert.equal(await savePassword.isDisabled(),true)
    await page.getByLabel('Konfirmasi Password',{exact:true}).fill('qa-chosen-password')
    await page.getByLabel('Private Key',{exact:true}).fill('   ')
    assert.equal(await savePassword.isDisabled(),true)
    await page.getByLabel('Private Key',{exact:true}).fill('qa-private-key')
    await savePassword.click()
    await page.getByRole('alert').filter({hasText:'Private key tidak valid.'}).waitFor()
    assert.deepEqual(resetPayloads,[{secretKey:'qa-private-key',newPassword:'qa-chosen-password'}])
    resetMode = 'network'
    await savePassword.click()
    await page.getByRole('alert').filter({hasText:'Koneksi bermasalah.'}).waitFor()
    resetMode = 'success'
    const resetRequest = page.waitForRequest(r=>r.url().endsWith('/auth/reset-password'))
    await savePassword.click()
    await resetRequest
    await page.getByRole('button',{name:'Menyimpan...'}).waitFor()
    assert.equal(await page.getByLabel('Private Key',{exact:true}).isDisabled(),true)
    assert.equal(await page.getByRole('button',{name:'Tutup dialog'}).isDisabled(),true)
    await page.keyboard.press('Escape')
    assert.equal(await page.locator('dialog').evaluate(el=>el.open),true)
    await page.locator('dialog form').evaluate(form=>form.requestSubmit())
    assert.equal(resetPayloads.length,3,'Pending submission must not issue another reset')
    releaseReset()
    await page.getByText('Password Berhasil Direset!',{exact:true}).waitFor()
    assert.ok(resetPayloads.every(body=>body.newPassword==='qa-chosen-password'))
    await page.getByRole('button',{name:'Kembali ke Login',exact:true}).click()
    check('Reset submits chosen password with private key only on confirmation; validates, handles failure, cancellation and pending submission')
    await page.getByLabel('Username',{exact:true}).fill('demo')
    await page.getByRole('button',{name:'Masuk',exact:true}).click()
    await page.getByRole('alert').filter({hasText:'Username atau password salah.'}).waitFor()
    assert.ok(page.url().endsWith('/login'))
    loginSucceeds = true
    await page.getByLabel('Password',{exact:true}).fill('correct-example-only')
    await page.getByRole('button',{name:'Masuk',exact:true}).click()
    await page.waitForURL('**/dashboard')
    await page.getByText('Input Transaksi / STT',{exact:true}).waitFor()
    assert.equal(await page.getByRole('link',{name:'Dashboard',exact:true}).getAttribute('href'),'/dashboard')
    check('Successful login redirects to migrated invoice dashboard (mocked API)')
    for (const width of [768,820,900,1024,1280]) {
      await page.setViewportSize({width,height:1000})
      const fits = await page.locator('header').evaluate(el => el.scrollWidth <= innerWidth)
      assert.ok(fits, 'Authenticated navigation overflow at ' + width)
    }
    await page.setViewportSize({width:1440,height:1000})
    check('Authenticated navigation fits tablet and desktop')
    await page.reload()
    await page.getByText('Input Transaksi / STT',{exact:true}).waitFor()
    await page.goto(base + '/login')
    await page.waitForURL('**/dashboard')
    await page.getByText('Input Transaksi / STT',{exact:true}).waitFor()
    await page.goto(base)
    await page.waitForURL('**/dashboard')
    check('Session recheck on reload and authenticated /login redirect (mocked API)')
    await page.getByRole('link',{name:'Tanda Tangan',exact:true}).click()
    await page.waitForURL('**/signatures')
    await page.getByRole('link',{name:'Dashboard',exact:true}).click()
    await page.waitForURL('**/dashboard')
    await page.getByRole('link',{name:'Storage',exact:true}).click()
    await page.waitForURL('**/storage')
    await page.getByRole('link',{name:'Trash',exact:true}).click()
    await page.waitForURL('**/trash')
    await page.getByRole('link',{name:'Dashboard',exact:true}).click()
    await page.waitForURL('**/dashboard')
    check('Existing app navigation returns to /dashboard')
    await page.getByRole('button',{name:'Keluar',exact:true}).click()
    await page.waitForURL('**/login')
    await page.getByRole('heading',{name:'Selamat datang kembali'}).waitFor()
    check('Logout returns to login')
    assert.deepEqual(errors, [], 'Browser runtime errors')
    check('No browser runtime errors across checked flows')
    fs.writeFileSync(path.join(out,'browser-results.json'),JSON.stringify({base,passed,requests,errors,mode:'API mocked; no backend/database touched'},null,2))
  } finally { await browser.close() }
}
main().catch(e => { console.error(e); process.exit(1) })
